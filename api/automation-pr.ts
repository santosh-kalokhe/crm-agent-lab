import type { VercelRequest, VercelResponse } from '@vercel/node'
import { createHash, timingSafeEqual } from 'node:crypto'

const REPO = 'santosh-kalokhe/crm-agent-lab'
const API = 'https://api.github.com'
const safeCompare = (a: string, b: string) => {
  const x = createHash('sha256').update(a).digest()
  const y = createHash('sha256').update(b).digest()
  return timingSafeEqual(x, y)
}
const github = async (path: string, token: string, method = 'GET', body?: unknown) => {
  const response = await fetch(API + path, {
    method,
    headers: { Authorization: 'Bearer ' + token, Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28', 'Content-Type': 'application/json' },
    ...(body ? { body: JSON.stringify(body) } : {}),
  })
  const data = await response.json()
  if (!response.ok) throw new Error('GitHub ' + response.status + ': ' + (data.message || 'request failed'))
  return data
}

export async function publishGeneratedTests(code: string, scenarioIds: string[], token: string) {
      const base = await github('/repos/' + REPO + '/git/ref/heads/main', token)
    const sha = base.object.sha as string
    const branch = 'agent/playwright-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 8)
    await github('/repos/' + REPO + '/git/refs', token, 'POST', { ref: 'refs/heads/' + branch, sha })
    const filename = 'tests/generated/agent3-' + branch.split('-').slice(1).join('-') + '.spec.ts'
    await github('/repos/' + REPO + '/contents/' + filename, token, 'PUT', {
      message: 'test: generate Playwright tests for ' + scenarioIds.join(', '),
      content: Buffer.from(code, 'utf8').toString('base64'), branch,
    })
    const pr = await github('/repos/' + REPO + '/pulls', token, 'POST', {
      title: 'test: Playwright automation for ' + scenarioIds.join(', '),
      head: branch, base: 'main', draft: true,
      body: 'Generated by Agent 3 from Agent 2 scenarios: ' + scenarioIds.join(', ') +
        '\n\nReview selectors, assertions, and test data before marking ready. Generated code has not been executed.',
    })
    return { url: pr.html_url as string, number: pr.number as number, branch, filename }
}

export default async function handler(req: VercelRequest, res: VercelResponse) {
  res.setHeader('Cache-Control', 'no-store')
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' })
  const secret = process.env.AGENT_PUBLISH_KEY
  const token = process.env.GITHUB_PR_TOKEN
  if (!secret || !token) return res.status(503).json({ error: 'Configure AGENT_PUBLISH_KEY and GITHUB_PR_TOKEN on the server.' })
  const { publishKey, code, scenarioIds } = req.body ?? {}
  if (typeof publishKey !== 'string' || !safeCompare(publishKey, secret))
    return res.status(403).json({ error: 'Invalid publishing authorization.' })
  if (typeof code !== 'string' || !code.trim() || code.length > 60000 ||
      !Array.isArray(scenarioIds) || scenarioIds.length < 1 || scenarioIds.length > 100 ||
      !scenarioIds.every((id: unknown) => typeof id === 'string' && /^TS-\d+$/i.test(id))) {
    return res.status(400).json({ error: 'Invalid generated test or scenario IDs.' })
  }
  // Generated code is untrusted: never execute it on this server.
  if (!/from\s+['"]@playwright\/test['"]/.test(code) ||
      /\b(?:child_process|execSync|spawnSync|eval)\b|\btest\.only\b|\bprocess\.env\b/.test(code) ||
      /\b(?:node:fs|node:child_process)\b/.test(code)) {
    return res.status(400).json({ error: 'Generated code did not pass basic safety checks.' })
  }
  try {
    const result = await publishGeneratedTests(code, scenarioIds, token)
    return res.status(200).json(result)
  } catch (error) {
    console.error('Agent 3 PR publishing failed', error instanceof Error ? error.message : 'unknown')
    return res.status(502).json({ error: 'Could not create GitHub pull request. Check token permissions and retry.' })
  }
}
